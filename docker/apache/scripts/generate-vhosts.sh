#!/bin/bash
set -e

HTDOCS_DIR="/var/www/html"
VHOSTS_DIR="/etc/apache2/vhosts.d"
DOMAIN_SUFFIX="${DOMAIN_SUFFIX:-local}"
DEFAULT_PHP_SERVICE="${DEFAULT_PHP_SERVICE:-php:9000}"

mkdir -p "$VHOSTS_DIR"

# Track current active project configs
ACTIVE_PROJECTS=()

if [ -d "$HTDOCS_DIR" ]; then
    for project_dir in "$HTDOCS_DIR"/*; do
        if [ -d "$project_dir" ]; then
            project_name=$(basename "$project_dir")

            # Ignore hidden directories like .git or system dirs
            if [[ "$project_name" =~ ^\. ]]; then
                continue
            fi

            ACTIVE_PROJECTS+=("auto-${project_name}.conf")

            # Detect Laravel / modern framework with public/ directory
            is_laravel=false
            if [ -d "${project_dir}/public" ] || [ -f "${project_dir}/artisan" ]; then
                is_laravel=true
                doc_root="${project_dir}/public"
            else
                doc_root="${project_dir}"
            fi

            php_service="$DEFAULT_PHP_SERVICE"
            vhost_conf="${VHOSTS_DIR}/auto-${project_name}.conf"

            cat <<EOF > "$vhost_conf"
# Auto-generated by LocalDevServer for ${project_name}
# Type: $([ "$is_laravel" = true ] && echo "Laravel" || echo "Standard PHP")
# Upstream PHP: ${php_service}

<VirtualHost *:80>
    ServerName ${project_name}.${DOMAIN_SUFFIX}
    ServerAlias www.${project_name}.${DOMAIN_SUFFIX} ${project_name}.localhost www.${project_name}.localhost
    DocumentRoot "${doc_root}"

    <Directory "${doc_root}">
        Options Indexes FollowSymLinks MultiViews
        AllowOverride All
        Require all granted
    </Directory>

    # Block sensitive files: .env, .git, and dotfiles
    <FilesMatch "^\.">
        Require all denied
    </FilesMatch>

    # Route PHP scripts to PHP-FPM
    <FilesMatch "\.php$">
        SetHandler "proxy:fcgi://${php_service}"
    </FilesMatch>

    DirectoryIndex index.php index.html

    ErrorLog "/var/log/apache2/${project_name}-error.log"
    CustomLog "/var/log/apache2/${project_name}-access.log" combined
</VirtualHost>
EOF
        fi
    done
fi

# Clean up stale configs for projects that no longer exist
for existing_conf in "$VHOSTS_DIR"/auto-*.conf; do
    if [ -f "$existing_conf" ]; then
        conf_basename=$(basename "$existing_conf")
        found=false
        for active in "${ACTIVE_PROJECTS[@]}"; do
            if [ "$conf_basename" == "$active" ]; then
                found=true
                break
            fi
        done
        if [ "$found" = false ]; then
            rm -f "$existing_conf"
        fi
    fi
done

exit 0

